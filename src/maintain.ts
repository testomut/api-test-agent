import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import type { LoadedSpec } from './spec/loader.js';
import type { Operation } from './types.js';
import { generate, type GenerateOptions, type GenerateResult } from './generate/generate.js';
import { summarize } from './generate/coverage.js';
import { runDiff } from './change/diff.js';
import type { OpenApiChange } from './change/types.js';
import { normalizeSpec } from './change/normalize.js';
import { readSource } from './change/network.js';
import { validateManifest, validateRegistry } from './cases/validate.js';
import { upsertDraftPr } from './pr.js';

/**
 * Automated test maintenance: spec diff → regenerate (deterministic, so only affected files change) → validate →
 * one Draft PR per suite with a short summary. Never merges, never runs tests against an environment, never
 * changes approved fixtures.
 */

export interface MaintainOptions {
  location: string;
  spec: LoadedSpec;
  ops: Operation[];
  generate: Omit<GenerateOptions, 'outDir'>;
  testsDir: string;
  base?: string;
  out: string;
  draftPr: boolean;
  allowNetwork: boolean;
  log: (m: string) => void;
}

export interface MaintainResult {
  changed: boolean;
  valid: boolean;
  summaryFile: string;
  pr?: { url: string; updated: boolean };
  files: { added: string[]; updated: string[]; headerOnly: string[]; removed: string[] };
  cases: { added: string[]; retired: string[] };
}

/** File content without the lines that only name the spec and generator (they change with every spec hash). */
const substance = (text: string) =>
  text
    .split('\n')
    .filter((l) => !/(Spec: .*\(hash [0-9a-f]+\)|Generated by api-test-agent|^\s*"?(specHash|hash|capturedRevision|source|revision|generatorVersion)"?\s*[:=])/.test(l))
    .join('\n');

async function contents(testsDir: string, files: Iterable<string>): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (const f of files) {
    const p = join(testsDir, f);
    if (existsSync(p)) out.set(f, substance(await readFile(p, 'utf8')));
  }
  return out;
}

async function snapshot(testsDir: string): Promise<{ files: Map<string, string>; cases: Map<string, string | undefined> }> {
  const manifestFile = join(testsDir, '_support', 'generation-manifest.json');
  const registryFile = join(testsDir, '_support', 'cases.json');
  const manifest = existsSync(manifestFile) ? JSON.parse(await readFile(manifestFile, 'utf8')) : { files: {} };
  const registry = existsSync(registryFile) ? JSON.parse(await readFile(registryFile, 'utf8')) : { cases: {} };
  return {
    files: new Map(Object.entries<any>(manifest.files ?? {}).map(([f, e]) => [f, e.sha256])),
    cases: new Map(Object.entries<any>(registry.cases ?? {}).map(([id, c]) => [id, c.status])),
  };
}

const fmt = (v: unknown) => (v === undefined ? '—' : JSON.stringify(v));

export async function maintain(o: MaintainOptions): Promise<MaintainResult> {
  await mkdir(o.out, { recursive: true });
  // 1. What changed in the spec (oasdiff). Without a baseline or the engine, everything is regenerated and said so.
  let changes: OpenApiChange[] = [];
  let diffNote = '';
  try {
    const d = await runDiff({ head: o.location, base: o.base, out: join(o.out, 'diff'), format: 'markdown', failOn: ['never'], allowEngineVersionMismatch: true, testsDir: o.testsDir, allowNetwork: o.allowNetwork, allowHosts: [], log: () => {} });
    changes = d.set.changes;
    if (d.set.blocked.length) diffNote = `diff blocked: ${d.set.blocked.map((b) => b.code).join(', ')}; the whole suite was regenerated`;
  } catch (e) {
    diffNote = `diff unavailable (${(e as Error).message.split('\n')[0]}); the whole suite was regenerated`;
  }
  const relevant = changes.filter((c) => c.testRelevant);
  o.log(`Spec changes: ${changes.length} (test-relevant ${relevant.length})${diffNote ? ` · ${diffNote}` : ''}`);

  // 2. Regenerate the whole suite: deterministic output, so unaffected files keep their bytes and hashes.
  const before = await snapshot(o.testsDir);
  const oldText = await contents(o.testsDir, before.files.keys());
  const previousCoverage = join(o.out, 'coverage-gaps.json');
  const oldGaps: Record<string, number> | undefined = existsSync(previousCoverage) ? JSON.parse(await readFile(previousCoverage, 'utf8')).summary?.gapsByCode ?? {} : undefined;
  const gen: GenerateResult = await generate(o.spec, o.ops, { ...o.generate, outDir: o.testsDir });
  const after = await snapshot(o.testsDir);
  const newGaps = summarize(gen.coverage);
  await writeFile(previousCoverage, JSON.stringify({ spec: o.location, hash: o.spec.hash, summary: { gapsByCode: newGaps }, operations: gen.coverage }, null, 2) + '\n');

  const newText = await contents(o.testsDir, after.files.keys());
  const touched = [...after.files.keys()].filter((f) => before.files.has(f) && before.files.get(f) !== after.files.get(f));
  const files = {
    added: [...after.files.keys()].filter((f) => !before.files.has(f)),
    updated: touched.filter((f) => oldText.get(f) !== newText.get(f)),
    /** Only the spec hash / generator lines changed: committed, but not a change a reviewer needs to read. */
    headerOnly: touched.filter((f) => oldText.get(f) === newText.get(f)),
    // A file is removed only when it is gone from disk (hand-written files are never deleted by the generator).
    removed: [...before.files.keys()].filter((f) => !after.files.has(f) && !existsSync(join(o.testsDir, f))),
  };
  const active = (m: Map<string, string | undefined>) => new Set([...m].filter(([, s]) => s !== 'retired').map(([id]) => id));
  const was = active(before.cases);
  const now = active(after.cases);
  const cases = { added: [...now].filter((id) => !was.has(id)), retired: [...was].filter((id) => !now.has(id)) };
  const changed = files.added.length + files.updated.length + files.headerOnly.length + files.removed.length > 0;

  // 3. Validate what was generated: registry against the head spec, manifest hashes.
  const problems: string[] = [];
  const registryFile = join(o.testsDir, '_support', 'cases.json');
  if (existsSync(registryFile)) {
    const reg = validateRegistry(await readFile(registryFile, 'utf8'), normalizeSpec(await readSource(o.location, { allowNetwork: o.allowNetwork, allowHosts: [] }), o.location));
    problems.push(...reg.errors.map((e) => `registry ${e.code} ${e.pointer}: ${e.reason}`), ...reg.blocked.map((b) => `registry BLOCKED ${b.code}: ${b.reason}`));
  }
  const man = await validateManifest(o.testsDir);
  problems.push(...man.findings.filter((f) => f.code !== 'CASE_REGISTRY_CHANGED').map((f) => `manifest ${f.code}: ${f.reason}`));
  const valid = problems.length === 0;

  // 4. Summary for the reviewer.
  const gapCodes = [...new Set([...Object.keys(oldGaps ?? {}), ...Object.keys(newGaps)])].sort();
  const gapRows = oldGaps
    ? gapCodes.filter((c) => (oldGaps[c] ?? 0) !== (newGaps[c] ?? 0)).map((c) => `| ${c} | ${oldGaps[c] ?? 0} | ${newGaps[c] ?? 0} |`)
    : gapCodes.map((c) => `| ${c} | unknown | ${newGaps[c]} |`);
  const needsReview = gen.coverage.flatMap((c) => c.gaps.filter((g) => g.code === 'INVALID_REVIEWED_CONFIG').map((g) => `- ${c.operation}: ${g.reason}`));
  const expectations = relevant.filter((c) => c.before !== undefined || c.after !== undefined);
  const fixtures = gen.files.filter((f) => /[\\/]_support[\\/]approved[\\/]/.test(f)).map((f) => relative(o.testsDir, f).replace(/\\/g, '/'));
  const L = [
    `## API test maintenance: ${o.spec.doc.info?.title ?? o.location}`,
    '',
    `Spec \`${o.location}\` (hash ${o.spec.hash.slice(0, 12)}). ${diffNote || `${changes.length} change(s), ${relevant.length} test-relevant.`}`,
    '',
    '### Changed operations',
    ...(relevant.length ? [...new Set(relevant.map((c) => c.operationKey))].map((k) => `- ${k}: ${relevant.filter((c) => c.operationKey === k).map((c) => c.kind + (c.breaking === 'yes' ? ' (breaking)' : '')).join(', ')}`) : ['- none detected']),
    '',
    '### Tests',
    `- files added ${files.added.length}, updated ${files.updated.length}, removed ${files.removed.length}; ${files.headerOnly.length} only got the new spec hash in their header`,
    `- cases added ${cases.added.length}, retired ${cases.retired.length}`,
    ...[...files.added.map((f) => `  - added \`${f}\``), ...files.updated.map((f) => `  - updated \`${f}\``), ...files.removed.map((f) => `  - removed \`${f}\``)].slice(0, 40),
    '',
    '### Expectations old → new',
    ...(expectations.length ? expectations.slice(0, 30).map((c) => `- ${c.operationKey} ${c.kind}${c.facet ? ` ${c.facet}` : ''}${c.pointer ? ` at ${c.pointer}` : ''}: ${fmt(c.before)} → ${fmt(c.after)}`) : ['- none']),
    '',
    '### Fixtures',
    ...(fixtures.length ? fixtures.map((f) => `- uses approved \`${f}\` (approved fixtures are never changed here; refresh them with \`fixtures refresh\`)`) : ['- none used']),
    '',
    ...(needsReview.length ? ['### Needs review: reviewed configuration no longer matches the spec', ...needsReview, '(these checks are not generated until the deps / fixture file is updated)', ''] : []),
    `### Coverage gaps${oldGaps ? '' : ' (no earlier report in this output directory: before is unknown)'}`,
    ...(gapRows.length ? ['| code | before | after |', '|---|---|---|', ...gapRows] : ['- unchanged']),
    '',
    '### Validation',
    ...(valid ? ['- case registry and generation manifest: valid'] : problems.slice(0, 20).map((p) => `- FAILED ${p}`)),
    '- generated tests were not run here: CI runs them on this branch. Review assertions; never edit one just to make it pass.',
  ];
  const summaryFile = join(o.out, 'maintenance-summary.md');
  await writeFile(summaryFile, L.join('\n') + '\n');
  await writeFile(join(o.out, 'maintenance-summary.json'), JSON.stringify({ changes: relevant.length, files, cases, gaps: { before: oldGaps, after: newGaps }, valid, problems }, null, 2) + '\n');
  o.log(`Tests: ${files.added.length} added, ${files.updated.length} updated (${files.headerOnly.length} header-only), ${files.removed.length} removed · cases +${cases.added.length} / retired ${cases.retired.length} · validation ${valid ? 'passed' : 'FAILED'}`);

  let pr: MaintainResult['pr'];
  if (o.draftPr && changed && valid) {
    const branch = `api-agent/maintain-${o.testsDir.replace(/[^\w-]+/g, '-').replace(/^-|-$/g, '')}`;
    const list = [...files.added, ...files.updated, ...files.headerOnly, ...files.removed, '_support/generation-manifest.json', '_support/cases.json'].map((f) => join(o.testsDir, f));
    pr = upsertDraftPr({ branch, files: list, title: `test(api): update generated tests for ${o.spec.doc.info?.title ?? 'the API'} (${o.spec.hash.slice(0, 8)})`, bodyFile: summaryFile, commitMessage: [`test(api): regenerate after spec change ${o.spec.hash.slice(0, 8)}`, 'Generated by api-test-agent maintain. Review before merging.'] });
    o.log(pr ? `Draft PR ${pr.updated ? 'updated' : 'opened'}: ${pr.url}` : 'Nothing to commit: Draft PR skipped.');
  } else if (o.draftPr) o.log(!changed ? 'Tests are up to date: no Draft PR.' : 'Validation failed: no Draft PR (see the summary).');
  return { changed, valid, summaryFile, ...(pr ? { pr } : {}), files, cases };
}
