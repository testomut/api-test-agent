import { execFileSync } from 'node:child_process';

const git = (...args: string[]) => execFileSync('git', args, { encoding: 'utf8' }).trim();

/**
 * Commits the given files on a fresh branch and opens a GitHub Draft PR with `gh`.
 * Never pushes to the default branch and never merges: a QA engineer reviews first.
 */
export async function openDraftPr(o: { files: string[]; title: string; bodyFile: string; hash: string }): Promise<string> {
  const base = git('rev-parse', '--abbrev-ref', 'HEAD');
  const branch = `api-agent/${o.hash}-${Date.now().toString(36)}`;
  git('switch', '-c', branch);
  try {
    git('add', '--', ...o.files);
    git('commit', '-m', o.title, '-m', 'Generated by api-test-agent. Review assertions and listed assumptions before merging.');
    git('push', '-u', 'origin', branch);
    return execFileSync('gh', ['pr', 'create', '--draft', '--base', base, '--head', branch, '--title', o.title, '--body-file', o.bodyFile], { encoding: 'utf8' }).trim();
  } finally {
    git('switch', base);
  }
}
