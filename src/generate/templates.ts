import type { Operation } from '../types.js';
import type { CrudChain } from './graph.js';
import type { NegCase } from './negative.js';

/** Payloads and assumptions for one confirmed resource chain. */
export interface ChainPlan {
  chain: CrudChain;
  createPayload: unknown;
  createSources: string[];
  updatePayload?: unknown;
  updateSources: string[];
  assumptions: string[];
}

export interface Meta {
  spec: string;
  hash: string;
  version: string;
}

/** Folder layout: <resource>/<method>[-by-id]/{positive,negative}.spec.ts */
export function operationFolder(op: Operation): { resource: string; action: string } {
  const segs = op.path.split('/').filter(Boolean);
  const statics = segs.filter((s) => !s.startsWith('{'));
  const resource = (statics.join('-') || 'root').replace(/[^\w.-]/g, '_');
  const byId = segs.length > 0 && segs[segs.length - 1].startsWith('{');
  return { resource, action: `${op.method}${byId ? '-by-id' : ''}` };
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lit = (v: unknown) => JSON.stringify(v, null, 2);
const label = (op: Operation) => op.operationId ?? op.key;
const successCodes = (op: Operation) => op.responses.map((r) => r.status).filter((s) => /^2\d\d$/.test(s));

function expectSuccess(op: Operation, v = 'res') {
  const ok = successCodes(op);
  return ok.length === 1
    ? `expect(${v}.status(), 'documented success status of ${label(op)}').toBe(${ok[0]});`
    : `expect([${ok.join(', ')}], 'documented success statuses of ${label(op)}').toContain(${v}.status());`;
}

/** TS template literal for the request path; the chain parameter comes from `idVar`. */
function pathExpr(op: Operation, chainParam?: string, idVar = 'id'): string {
  let p = op.path.replace(/^\//, '');
  for (const param of op.params.filter((x) => x.in === 'path')) {
    const value = param.name === chainParam ? `\${encodeURIComponent(${idVar})}` : `\${encodeURIComponent(${q(String(param.knownValue))})}`;
    p = p.replace(`{${param.name}}`, value);
  }
  return '`' + p + '`';
}

function requiredQuery(op: Operation): Record<string, unknown> {
  return Object.fromEntries(op.params.filter((p) => p.in === 'query' && p.required && p.knownValue !== undefined).map((p) => [p.name, p.knownValue]));
}

function header(kind: 'positive' | 'negative', op: Operation, meta: Meta, extra: string[]): string[] {
  return [
    `// ${op.key} · ${kind} cases. Generated by api-test-agent ${meta.version}.`,
    `// Spec: ${meta.spec} (hash ${meta.hash}). Regenerated on spec change: put hand-written cases in separate files.`,
    `// Review before merging; never edit assertions just to make a test pass.`,
    ...extra.map((e) => `// ${e}`),
  ];
}

/* ------------------------------------------------------------------ helpers per resource */

export function renderResourceHelpers(plan: ChainPlan, meta: Meta): string {
  const { chain } = plan;
  const c = chain.create;
  const d = chain.delete!;
  const L = [
    `// Data helpers for ${chain.name}. Generated by api-test-agent ${meta.version}.`,
    `// Dependency source: ${chain.source}`,
    `// createPayload sources: ${plan.createSources.join('; ') || 'none'}`,
    ...(plan.updatePayload !== undefined ? [`// updatePayload sources: ${plan.updateSources.join('; ')}`] : []),
    `import { expect, type APIRequestContext, type APIResponse } from '@playwright/test';`,
    `import { expectContract, readPointer } from './contract-assert.js';`,
    '',
    `export const createPayload = ${lit(plan.createPayload)};`,
    '',
  ];
  if (plan.updatePayload !== undefined) L.push(`export const updatePayload = ${lit(plan.updatePayload)};`, '');
  L.push(
    `/** ${c.key}: creates a resource for a test and returns its id (at $response.body#${chain.idPointer}). */`,
    `export async function create(request: APIRequestContext, data: unknown = createPayload): Promise<{ id: string; body: unknown }> {`,
    `  const res = await request.${c.method}(${q(c.path.replace(/^\//, ''))}, { data });`,
    `  ${expectSuccess(c)}`,
    `  const body = await expectContract(res, '${c.method}', ${q(c.path)});`,
    `  const id = String(readPointer(body, ${q(chain.idPointer)}) ?? '');`,
    `  expect(id, 'identifier at $response.body#${chain.idPointer}').not.toBe('');`,
    `  return { id, body };`,
    `}`,
    '',
    `/** ${d.key}: best-effort cleanup, never fails the test. */`,
    `export async function remove(request: APIRequestContext, id: string): Promise<void> {`,
    `  await request.delete(${pathExpr(d, chain.param)}).catch(() => undefined);`,
    `}`,
    '',
    `/** Cleanup for negative create cases: if the API wrongly accepted the payload, delete what it created. */`,
    `export async function removeIfCreated(request: APIRequestContext, res: APIResponse): Promise<void> {`,
    `  if (!res.ok()) return;`,
    `  const id = readPointer(await res.json().catch(() => undefined), ${q(chain.idPointer)});`,
    `  if (id !== undefined && id !== null) await remove(request, String(id));`,
    `}`,
  );
  return L.join('\n') + '\n';
}

/* ------------------------------------------------------------------ positive */

export interface PositiveInput {
  op: Operation;
  plan?: ChainPlan; // set when the operation belongs to a confirmed chain
  helpers?: string; // import path of the resource helpers
}

export function renderPositive({ op, plan, helpers }: PositiveInput, meta: Meta): string {
  const chain = plan?.chain;
  const role = chain ? (chain.create === op ? 'create' : chain.read === op ? 'read' : chain.update === op ? 'update' : chain.delete === op ? 'delete' : undefined) : undefined;
  const extra: string[] = [];
  if (chain) extra.push(`Preconditions and cleanup: ${chain.source}`);
  if (role === 'update' && chain?.read) extra.push(`ASSUMPTION (not in spec, reviewer must confirm): ${plan!.assumptions.find((a) => a.startsWith('after')) ?? 'read after update returns the new values'}`);

  const L = header('positive', op, meta, extra);
  L.push(`import { test, expect } from '../../_support/fixtures.js';`);
  L.push(`import { expectContract${role ? ', readPointer' : ''} } from '../../_support/contract-assert.js';`);
  if (role) L.push(`import * as resource from '${helpers}';`);
  L.push('', `test.describe('${op.key} · positive', () => {`);

  if (!role) {
    const query = requiredQuery(op);
    const opts = Object.keys(query).length ? `, { params: ${JSON.stringify(query)} }` : '';
    L.push(
      `  test('returns the documented success response', async ({ request }) => {`,
      `    const res = await request.${op.method}(${pathExpr(op)}${opts});`,
      `    ${expectSuccess(op)}`,
      `    await expectContract(res, '${op.method}', ${q(op.path)});`,
      `  });`,
    );
  } else if (role === 'create') {
    L.push(
      `  test('creates a resource from the documented example payload', async ({ request }) => {`,
      `    let id: string | undefined;`,
      `    try {`,
      `      const res = await request.${op.method}(${pathExpr(op)}, { data: resource.createPayload });`,
      `      ${expectSuccess(op)}`,
      `      const body = await expectContract(res, '${op.method}', ${q(op.path)});`,
      `      id = String(readPointer(body, ${q(chain!.idPointer)}) ?? '');`,
      `      expect(id, 'identifier at $response.body#${chain!.idPointer}').not.toBe('');`,
      `    } finally {`,
      `      if (id) await resource.remove(request, id);`,
      `    }`,
      `  });`,
    );
  } else if (role === 'read') {
    L.push(
      `  test('returns the resource created in the precondition', async ({ request }) => {`,
      `    const { id } = await resource.create(request);`,
      `    try {`,
      `      const res = await request.${op.method}(${pathExpr(op, chain!.param)});`,
      `      ${expectSuccess(op)}`,
      `      const body = await expectContract(res, '${op.method}', ${q(op.path)});`,
      `      expect(String(readPointer(body, ${q(chain!.idPointer)})), 'same resource').toBe(id);`,
      `    } finally {`,
      `      await resource.remove(request, id);`,
      `    }`,
      `  });`,
    );
  } else if (role === 'update') {
    const r = chain!.read;
    L.push(
      `  test('applies the documented example update', async ({ request }) => {`,
      `    const { id } = await resource.create(request);`,
      `    try {`,
      `      const res = await request.${op.method}(${pathExpr(op, chain!.param)}, { data: resource.updatePayload });`,
      `      ${expectSuccess(op)}`,
      `      await expectContract(res, '${op.method}', ${q(op.path)});`,
    );
    if (r) {
      L.push(
        `      // ASSUMPTION: the read operation returns the updated values.`,
        `      const read = await request.${r.method}(${pathExpr(r, chain!.param)});`,
        `      ${expectSuccess(r, 'read')}`,
        `      expect(await expectContract(read, '${r.method}', ${q(r.path)})).toMatchObject(resource.updatePayload);`,
      );
    }
    L.push(`    } finally {`, `      await resource.remove(request, id);`, `    }`, `  });`);
  } else if (role === 'delete') {
    const r = chain!.read;
    const gone = r && r.responses.some((x) => x.status === '404');
    L.push(
      `  test('deletes the resource created in the precondition', async ({ request }) => {`,
      `    const { id } = await resource.create(request);`,
      `    let deleted = false;`,
      `    try {`,
      `      const res = await request.${op.method}(${pathExpr(op, chain!.param)});`,
      `      ${expectSuccess(op)}`,
      `      await expectContract(res, '${op.method}', ${q(op.path)});`,
      `      deleted = true;`,
    );
    if (gone) {
      L.push(
        `      const read = await request.${r!.method}(${pathExpr(r!, chain!.param)});`,
        `      expect(read.status(), 'documented 404 after delete').toBe(404);`,
        `      await expectContract(read, '${r!.method}', ${q(r!.path)});`,
      );
    }
    L.push(`    } finally {`, `      if (!deleted) await resource.remove(request, id);`, `    }`, `  });`);
  }
  L.push(`});`);
  return L.join('\n') + '\n';
}

/* ------------------------------------------------------------------ negative */

export interface NegativeInput {
  op: Operation;
  plan?: ChainPlan;
  helpers?: string;
  validation: string[]; // documented validation rejections: 400 / 422 / 4XX
  bodyCases: NegCase[];
  queryCases: NegCase[];
  notFound?: { idExpr: string; param: string };
  unauthorized: boolean;
}

export function renderNegative(n: NegativeInput, meta: Meta): string {
  const { op, plan } = n;
  const chain = plan?.chain;
  const isCreate = chain?.create === op;
  const needsExisting = !!chain && chain.create !== op && op.params.some((p) => p.in === 'path' && p.name === chain.param);
  const usesHelpers = !!chain && (isCreate || needsExisting);
  const usesUuid = n.notFound?.idExpr === 'randomUUID()';

  const L = header('negative', op, meta, [
    'Expected statuses come from the documented responses of this operation; each case breaks one documented rule.',
  ]);
  if (usesUuid) L.push(`import { randomUUID } from 'node:crypto';`);
  L.push(`import { test } from '../../_support/fixtures.js';`);
  L.push(`import { expectRejected } from '../../_support/contract-assert.js';`);
  if (usesHelpers) L.push(`import * as resource from '${n.helpers}';`);
  L.push('', `const rejection = ${JSON.stringify(n.validation)}; // documented in the spec`, '');
  L.push(`test.describe('${op.key} · negative', () => {`);

  const send = (indent: string, extraOpts: string, idVar = 'id') =>
    `${indent}const res = await request.${op.method}(${pathExpr(op, chain?.param, idVar)}${extraOpts});`;

  if (n.bodyCases.length) {
    L.push(`  const invalidBodies = [`);
    for (const c of n.bodyCases) L.push(`    { title: ${q(c.title)}, source: ${q(c.source)}, data: ${JSON.stringify(c.data)} },`);
    L.push(`  ];`, '');
    L.push(`  for (const c of invalidBodies) {`);
    L.push(`    test(\`rejects invalid body: \${c.title}\`, async ({ request }) => {`);
    if (needsExisting) {
      L.push(`      const { id } = await resource.create(request);`, `      try {`);
      L.push(send('        ', ', { data: c.data }'));
      L.push(`        await expectRejected(res, rejection, '${op.method}', ${q(op.path)});`, `      } finally {`, `        await resource.remove(request, id);`, `      }`);
    } else {
      L.push(send('      ', ', { data: c.data }'));
      if (isCreate) L.push(`      await resource.removeIfCreated(request, res);`);
      L.push(`      await expectRejected(res, rejection, '${op.method}', ${q(op.path)});`);
    }
    L.push(`    });`, `  }`, '');
  }

  if (n.queryCases.length) {
    L.push(`  const invalidQueries = [`);
    for (const c of n.queryCases) L.push(`    { title: ${q(c.title)}, source: ${q(c.source)}, params: ${JSON.stringify(c.query)} },`);
    L.push(`  ];`, '');
    L.push(`  for (const c of invalidQueries) {`);
    L.push(`    test(\`rejects invalid query: \${c.title}\`, async ({ request }) => {`);
    L.push(`      const res = await request.${op.method}(${pathExpr(op)}, { params: c.params });`);
    L.push(`      await expectRejected(res, rejection, '${op.method}', ${q(op.path)});`);
    L.push(`    });`, `  }`, '');
  }

  if (n.notFound) {
    // A body is needed only for update operations (always in a chain, so helpers are imported).
    const body = plan?.updatePayload !== undefined && chain?.update === op ? `, { data: resource.updatePayload }` : '';
    L.push(`  test('returns documented 404 for an id that does not exist', async ({ request }) => {`);
    L.push(`    const missingId = String(${n.notFound.idExpr});`);
    L.push(`    const res = await request.${op.method}(${pathExpr(op, chain?.param ?? n.notFound.param, 'missingId')}${body});`);
    L.push(`    await expectRejected(res, ['404'], '${op.method}', ${q(op.path)});`, `  });`, '');
  }

  if (n.unauthorized) {
    L.push(`  test('returns documented 401 without credentials', async ({ playwright, baseURL }) => {`);
    // Explicit headers: inside a test, newContext() would otherwise inherit the project's auth header.
    L.push(`    const anonymous = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { accept: 'application/json' }, httpCredentials: undefined });`);
    L.push(`    try {`);
    L.push(`      const res = await anonymous.${op.method}(${pathExpr(op, chain?.param, "'unused'")});`);
    L.push(`      await expectRejected(res, ['401'], '${op.method}', ${q(op.path)});`);
    L.push(`    } finally {`, `      await anonymous.dispose();`, `    }`, `  });`);
  }
  L.push(`});`);
  return L.join('\n') + '\n';
}

/* ------------------------------------------------------------------ shared support */

export const CONTRACT_ASSERT = `// Generated by api-test-agent. Bridges Playwright responses to the OpenAPI contract.
import { expect, type APIResponse } from '@playwright/test';
import { ContractValidator } from './contract.js';
import { spec } from './openapi.snapshot.js';

const validator = new ContractValidator(spec);

async function readBody(res: APIResponse): Promise<{ contentType: string | null; body: unknown }> {
  const contentType = res.headers()['content-type'] ?? null;
  const text = await res.text();
  let body: unknown = text;
  if (contentType?.includes('json')) {
    try {
      body = text.length ? JSON.parse(text) : null;
    } catch {
      body = undefined;
    }
  }
  return { contentType, body };
}

/** Validates status, content type and body against the spec. Failures are tagged CONTRACT_MISMATCH. */
export async function expectContract(res: APIResponse, method: string, path: string): Promise<unknown> {
  const { contentType, body } = await readBody(res);
  const r = validator.validateResponse({ method, path, status: res.status(), contentType, body });
  expect(r.ok, \`CONTRACT_MISMATCH \${method.toUpperCase()} \${path} (\${r.kind}): \${r.errors.join('; ')}\`).toBe(true);
  return body;
}

/** The request must be rejected with one of the documented statuses ("400", "422", "4XX"...), then match the contract. */
export async function expectRejected(res: APIResponse, documented: string[], method: string, path: string): Promise<unknown> {
  const s = String(res.status());
  const ok = documented.some((c) => c === s || (/^\\dXX$/i.test(c) && c[0] === s[0]));
  expect(ok, \`CONTRACT_MISMATCH \${method.toUpperCase()} \${path}: expected documented rejection \${documented.join('/')}, got \${s}\`).toBe(true);
  return expectContract(res, method, path);
}

export function readPointer(body: unknown, pointer: string): unknown {
  return pointer
    .split('/')
    .slice(1)
    .map((p) => p.replace(/~1/g, '/').replace(/~0/g, '~'))
    .reduce<any>((node, key) => (node == null ? undefined : node[key]), body);
}
`;
