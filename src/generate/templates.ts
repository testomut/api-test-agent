import type { Operation } from '../types.js';
import type { CrudChain } from './graph.js';

export interface ChainPlan {
  chain: CrudChain;
  createPayload: unknown;
  createSources: string[];
  updatePayload?: unknown;
  updateSources: string[];
  /** Assertions that are not written in the spec; listed in the PR for the reviewer. */
  assumptions: string[];
}

const ident = (s: string) => s.replace(/[^A-Za-z0-9_$]/g, '_').replace(/^(\d)/, '_$1');
const lit = (v: unknown) => JSON.stringify(v, null, 2);
const rel = (p: string) => p.replace(/^\//, '');
const successStatuses = (op: Operation) => op.responses.map((r) => r.status).filter((s) => /^2\d\d$/.test(s)).map(Number);
const has404 = (op?: Operation) => !!op?.responses.some((r) => r.status === '404' || r.status === '4XX');

function expectStatus(op: Operation, v: string) {
  const ok = successStatuses(op);
  return ok.length === 1
    ? `expect(${v}.status(), 'documented success status of ${op.operationId ?? op.key}').toBe(${ok[0]});`
    : `expect([${ok.join(', ')}], 'documented success statuses of ${op.operationId ?? op.key}').toContain(${v}.status());`;
}

export function renderCrudTest(plan: ChainPlan, meta: { spec: string; hash: string; version: string }): string {
  const { chain } = plan;
  const id = ident(chain.param);
  const itemPath = (op: Operation) => '`' + rel(op.path).replace(`{${chain.param}}`, `\${${id}}`) + '`';
  const ops = [chain.create, chain.read, chain.update, chain.delete].filter(Boolean) as Operation[];
  const title = ops.map((o) => o.operationId ?? o.key).join(' → ');

  const L: string[] = [];
  L.push(`// Generated by api-test-agent ${meta.version}. Review before merging; do not edit assertions to make it pass.`);
  L.push(`// Spec: ${meta.spec} (hash ${meta.hash})`);
  L.push(`// Dependency source: ${chain.source}`);
  L.push(`// Create payload sources: ${plan.createSources.join('; ') || 'none'}`);
  if (plan.updatePayload !== undefined) L.push(`// Update payload sources: ${plan.updateSources.join('; ')}`);
  for (const a of plan.assumptions) L.push(`// ASSUMPTION (not in spec, reviewer must confirm): ${a}`);
  L.push(`import { test, expect } from '@playwright/test';`);
  L.push(`import { expectContract, readPointer } from './_support/contract-assert.js';`, '');
  L.push(`const createPayload = ${lit(plan.createPayload)};`);
  if (plan.updatePayload !== undefined) L.push(`const updatePayload = ${lit(plan.updatePayload)};`);
  L.push('');
  L.push(`test.describe('${chain.name}', () => {`);
  L.push(`  test('${title}', async ({ request }) => {`);
  L.push(`    let ${id}: string | undefined;`);
  L.push(`    let deleted = false;`);
  L.push(`    try {`);

  const c = chain.create;
  L.push(`      await test.step('${c.operationId ?? c.key}: ${c.key}', async () => {`);
  L.push(`        const res = await request.${c.method}('${rel(c.path)}', { data: createPayload });`);
  L.push(`        ${expectStatus(c, 'res')}`);
  L.push(`        const body = await expectContract(res, '${c.method}', '${c.path}');`);
  L.push(`        ${id} = String(readPointer(body, '${chain.idPointer}') ?? '');`);
  L.push(`        expect(${id}, 'identifier at $response.body#${chain.idPointer}').not.toBe('');`);
  L.push(`      });`, '');

  const readStep = (label: string, extra: string[]) => {
    const r = chain.read!;
    L.push(`      await test.step('${label}', async () => {`);
    L.push(`        const res = await request.get(${itemPath(r)});`);
    L.push(`        ${expectStatus(r, 'res')}`);
    L.push(`        const body = await expectContract(res, 'get', '${r.path}');`);
    L.push(`        expect(String(readPointer(body, '${chain.idPointer}')), 'read returns the created resource').toBe(${id});`);
    for (const e of extra) L.push(`        ${e}`);
    L.push(`      });`, '');
  };

  if (chain.read) readStep(`${chain.read.operationId ?? chain.read.key}: read after create`, []);

  if (chain.update && plan.updatePayload !== undefined) {
    const u = chain.update;
    L.push(`      await test.step('${u.operationId ?? u.key}: ${u.key}', async () => {`);
    L.push(`        const res = await request.${u.method}(${itemPath(u)}, { data: updatePayload });`);
    L.push(`        ${expectStatus(u, 'res')}`);
    L.push(`        await expectContract(res, '${u.method}', '${u.path}');`);
    L.push(`      });`, '');
    if (chain.read) readStep(`${chain.read.operationId ?? chain.read.key}: read after update`, [`expect(body).toMatchObject(updatePayload);`]);
  }

  if (chain.delete) {
    const d = chain.delete;
    L.push(`      await test.step('${d.operationId ?? d.key}: ${d.key}', async () => {`);
    L.push(`        const res = await request.delete(${itemPath(d)});`);
    L.push(`        ${expectStatus(d, 'res')}`);
    L.push(`        await expectContract(res, 'delete', '${d.path}');`);
    L.push(`        deleted = true;`);
    L.push(`      });`, '');
    if (chain.read && has404(chain.read)) {
      L.push(`      await test.step('${chain.read.operationId ?? chain.read.key}: gone after delete', async () => {`);
      L.push(`        const res = await request.get(${itemPath(chain.read)});`);
      L.push(`        expect(res.status(), 'documented 404 after delete').toBe(404);`);
      L.push(`        await expectContract(res, 'get', '${chain.read.path}');`);
      L.push(`      });`);
    }
  }
  L.push(`    } finally {`);
  if (chain.delete) {
    L.push(`      // Cleanup runs even when an assertion above failed.`);
    L.push(`      if (${id} && !deleted) await request.delete(${itemPath(chain.delete)});`);
  }
  L.push(`    }`);
  L.push(`  });`);
  L.push(`});`);
  return L.join('\n') + '\n';
}

export const CONTRACT_ASSERT = `// Generated by api-test-agent. Bridges Playwright responses to the OpenAPI contract.
import { expect, type APIResponse } from '@playwright/test';
import { ContractValidator } from './contract.js';
import { spec } from './openapi.snapshot.js';

const validator = new ContractValidator(spec);

/** Validates status, content type and body against the spec. Failures are tagged CONTRACT_MISMATCH. */
export async function expectContract(res: APIResponse, method: string, path: string): Promise<unknown> {
  const contentType = res.headers()['content-type'] ?? null;
  const text = await res.text();
  let body: unknown = text;
  if (contentType?.includes('json')) {
    try {
      body = text.length ? JSON.parse(text) : null;
    } catch {
      body = undefined;
    }
  }
  const r = validator.validateResponse({ method, path, status: res.status(), contentType, body });
  expect(r.ok, \`CONTRACT_MISMATCH \${method.toUpperCase()} \${path} (\${r.kind}): \${r.errors.join('; ')}\`).toBe(true);
  return body;
}

export function readPointer(body: unknown, pointer: string): unknown {
  return pointer
    .split('/')
    .slice(1)
    .map((p) => p.replace(/~1/g, '/').replace(/~0/g, '~'))
    .reduce<any>((node, key) => (node == null ? undefined : node[key]), body);
}
`;
