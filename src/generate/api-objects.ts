/**
 * API objects (the API counterpart of page objects) for generated TypeScript suites.
 *
 *   _support/api/generated/ApiBase.ts        shared base: one place that sends requests
 *   _support/api/generated/<Name>ApiBase.ts  one method per operation; REWRITTEN on every generate
 *   _support/api/<Name>Api.ts                extends the base; created once, never overwritten:
 *                                            hand-written reusable requests and flows live here
 *   _support/api/generated/apis.ts           createApis(request) → { brands: BrandsApi, ... }
 *
 * Operations are grouped by the first static path segment (/brands, /brands/{id},
 * /brands/search → BrandsApi). Methods return the raw APIResponse: assertions stay in tests.
 */
import type { Operation } from '../types.js';

export interface ApiRef {
  /** Property on the apis object, e.g. "brands" (api.brands). */
  prop: string;
  /** Hand-written class, e.g. "BrandsApi". */
  className: string;
  /** Method name, e.g. "getBrands". */
  method: string;
  /** Path parameter names in path order (the method's leading arguments). */
  pathParams: string[];
}

export interface ApiGroup {
  prop: string;
  className: string;
  ops: Operation[];
}

const words = (s: string) => s.split(/[^A-Za-z0-9]+|(?<=[a-z0-9])(?=[A-Z])/).filter(Boolean);
const pascal = (s: string) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const camel = (s: string) => {
  const p = pascal(s);
  return p ? p[0].toLowerCase() + p.slice(1) : p;
};
const RESERVED = new Set(['constructor', 'request', 'send', 'segment', 'prototype', 'delete', 'new', 'class', 'function', 'default']);
const ident = (s: string, fallback: string) => {
  let v = camel(s) || fallback;
  if (/^\d/.test(v)) v = `_${v}`;
  return RESERVED.has(v) ? `${v}Op` : v;
};

export function apiGroupName(op: Operation): string {
  return op.path.split('/').filter((s) => s && !s.startsWith('{'))[0] ?? 'root';
}

/** Deterministic names for every operation; duplicates inside a class get a numeric suffix. */
export function buildApiIndex(ops: Operation[]): { refs: Map<Operation, ApiRef>; groups: ApiGroup[] } {
  const refs = new Map<Operation, ApiRef>();
  const groups = new Map<string, ApiGroup>();
  const usedProps = new Set<string>();
  for (const op of ops) {
    const g = apiGroupName(op);
    let group = groups.get(g);
    if (!group) {
      let prop = ident(g, 'root');
      while (usedProps.has(prop)) prop += '_';
      usedProps.add(prop);
      group = { prop, className: `${pascal(prop)}Api`, ops: [] };
      groups.set(g, group);
    }
    group.ops.push(op);
  }
  for (const group of groups.values()) {
    const used = new Set<string>();
    for (const op of group.ops) {
      const base = ident(op.operationId ?? `${op.method} ${op.path.replace(/\{([^}]+)\}/g, ' by $1 ')}`, op.method);
      let name = base;
      for (let i = 2; used.has(name); i++) name = `${base}${i}`;
      used.add(name);
      refs.set(op, { prop: group.prop, className: group.className, method: name, pathParams: op.params.filter((p) => p.in === 'path').map((p) => p.name) });
    }
  }
  return { refs, groups: [...groups.values()] };
}

/** `api.brands.getBrand(id, { params })` for a test or helper. */
export function apiCall(ref: ApiRef, target: string, args: string[], options?: string): string {
  return `${target}.${ref.prop}.${ref.method}(${[...args, ...(options ? [options] : [])].join(', ')})`;
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export const API_BASE = (version: string) => `// Generated by api-test-agent ${version}. Rewritten on every generate: do not edit.
import type { APIRequestContext, APIResponse } from '@playwright/test';

/** Playwright request options (params, data, form, multipart, headers, timeout...) without the method. */
export type RequestOptions = Omit<NonNullable<Parameters<APIRequestContext['fetch']>[1]>, 'method'>;
export type PathValue = string | number;

/** Every generated and hand-written API object sends its requests through here. */
export class ApiBase {
  constructor(protected readonly request: APIRequestContext) {}

  /** Path relative to baseURL, e.g. "brands/123". */
  protected send(method: string, path: string, options: RequestOptions = {}): Promise<APIResponse> {
    return this.request.fetch(path, { ...options, method: method.toUpperCase() });
  }

  protected segment(value: PathValue): string {
    return encodeURIComponent(String(value));
  }
}
`;

export function renderApiBaseClass(group: ApiGroup, refs: Map<Operation, ApiRef>, version: string): string {
  const L = [
    `// ${group.className} requests generated from the spec by api-test-agent ${version}.`,
    `// Rewritten on every generate: do not edit. Add your own requests to ../${group.className}.ts.`,
    `import type { APIResponse } from '@playwright/test';`,
    `import { ApiBase, type PathValue, type RequestOptions } from './ApiBase.js';`,
    '',
    `export class ${group.className}Base extends ApiBase {`,
  ];
  group.ops.forEach((op, i) => {
    const ref = refs.get(op)!;
    const args = ref.pathParams.map((p) => ident(p, 'id'));
    let path = op.path.replace(/^\//, '');
    ref.pathParams.forEach((p, j) => (path = path.replace(`{${p}}`, `\${this.segment(${args[j]})}`)));
    const doc = [op.key, op.operationId, op.summary].filter(Boolean).join(' · ').replace(/\*\//g, '*\\/');
    if (i) L.push('');
    L.push(
      `  /** ${doc}${op.deprecated ? ' (deprecated)' : ''} */`,
      `  ${ref.method}(${[...args.map((a) => `${a}: PathValue`), 'options: RequestOptions = {}'].join(', ')}): Promise<APIResponse> {`,
      `    return this.send(${q(op.method)}, \`${path}\`, options);`,
      `  }`,
    );
  });
  L.push(`}`);
  return L.join('\n') + '\n';
}

/** Created once; the generator never overwrites it. */
