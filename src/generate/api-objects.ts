export function renderApis(groups: ApiGroup[], version: string): string {
  const sorted = [...groups].sort((a, b) => a.prop.localeCompare(b.prop));
  return [
    `// Generated by api-test-agent ${version}. Rewritten on every generate: do not edit.`,
    `// One API object per resource; the classes are the hand-written ones in ../ (they extend the generated bases).`,
    `import type { APIRequestContext } from '@playwright/test';`,
    ...sorted.map((g) => `import { ${g.className} } from '../${g.className}.js';`),
    '',
    `export function createApis(request: APIRequestContext) {`,
    `  return {`,
    ...sorted.map((g) => `    ${g.prop}: new ${g.className}(request),`),
    `  };`,
    `}`,
    '',
    `export type Apis = ReturnType<typeof createApis>;`,
  ].join('\n') + '\n';
}
