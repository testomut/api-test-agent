export const pyName = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1');
const pyClass = (s: string) => pyName(s).split('_').filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Resource';
const str = (s: string) => JSON.stringify(s); // a JSON string literal is a valid Python string literal
const label = (op: Operation) => op.operationId ?? op.key;
const successCodes = (op: Operation) => op.responses.map((r) => r.status).filter((s) => /^2\d\d$/.test(s));

/** JSON value → Python literal. */
export function pyLit(v: unknown, indent = 0): string {
  const pad = ' '.repeat(indent);
  if (v === null || v === undefined) return 'None';
  if (v === true) return 'True';
  if (v === false) return 'False';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'None';
  if (typeof v === 'string') return str(v);
  if (Array.isArray(v)) return v.length ? `[${v.map((x) => pyLit(x, indent)).join(', ')}]` : '[]';
  const entries = Object.entries(v as Record<string, unknown>);
  if (!entries.length) return '{}';
  return `{\n${entries.map(([k, x]) => `${pad}    ${str(k)}: ${pyLit(x, indent + 4)},`).join('\n')}\n${pad}}`;
}

export function assertSuccess(op: Operation, v = 'res'): string {
  const ok = successCodes(op);
  return ok.length === 1
    ? `assert ${v}.status_code == ${ok[0]}, f"documented success status of ${label(op)} is ${ok[0]}, got {${v}.status_code}"`
    : `assert ${v}.status_code in (${ok.join(', ')}), f"documented success statuses of ${label(op)}: ${ok.join('/')}, got {${v}.status_code}"`;
}

/** Python f-string for the request path; the chain parameter comes from `idVar`. */
export function pathExpr(op: Operation, chainParam?: string, idVar = 'resource_id'): string {
  let p = op.path.replace(/^\//, '').replace(/[{}]/g, (c) => c + c); // escape braces for the f-string
  for (const param of op.params.filter((x) => x.in === 'path')) {
    // Inner literals use single quotes: the f-string itself is double-quoted (Python < 3.12 forbids reuse).
    const known = `'${String(param.knownValue).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const value = param.name === chainParam ? `{quote(str(${idVar}), safe='')}` : `{quote(${known}, safe='')}`;
    p = p.replace(`{{${param.name}}}`, value);
  }
  return `f${str(p)}`;
}

/** Keyword arguments with the operation's required query / header / cookie parameters (documented values). */
export function pyRequired(op: Operation, skip: ('params' | 'headers')[] = []): string {
  const r = requiredRequest(op);
  return [
    Object.keys(r.params).length && !skip.includes('params') ? `, params=${pyLit(r.params, 4)}` : '',
    Object.keys(r.headers).length && !skip.includes('headers') ? `, headers=${pyLit(r.headers, 4)}` : '',
  ].join('');
}

/** Path whose parameters come from the row's "path" values, else their documented values. */
function pathFromParts(op: Operation): string {
  let p = op.path.replace(/^\//, '').replace(/[{}]/g, (c) => c + c);
  for (const param of op.params.filter((x) => x.in === 'path')) {
    const known = param.knownValue === undefined ? "'unused'" : `'${String(param.knownValue).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    p = p.replace(`{{${param.name}}}`, `{quote(str(path.get('${param.name}', ${known})), safe='')}`);
  }
  return `f${str(p)}`;
}

