export function resourceModule(plan: ChainPlan): string {
  return `${pyName(plan.chain.create.path.split('/').filter((s) => s && !s.startsWith('{')).join('_') || 'root')}_resource`;
}

export function renderPyResource(plan: ChainPlan, meta: Meta): string {
  const { chain } = plan;
  const c = chain.create;
  const d = chain.delete!;
  const cls = pyClass(resourceModule(plan).replace(/_resource$/, ''));
  return `"""Data helpers for ${chain.name}. Generated by api-test-agent ${meta.version}.

Dependency source: ${chain.source}
CREATE_PAYLOAD sources: ${plan.createSources.join('; ') || 'none'}${plan.updatePayload !== undefined ? `\nUPDATE_PAYLOAD sources: ${plan.updateSources.join('; ')}` : ''}
${[...uniqueNote(c, plan.uniqueCreate, ''), ...(chain.update ? uniqueNote(chain.update, plan.uniqueUpdate, '') : [])].join('\n')}
"""
import copy
import uuid
from urllib.parse import quote

from contract import read_pointer, report_cleanup_failure

# The documented example payloads, unchanged. Requests use new_create_payload() / new_update_payload().
CREATE_PAYLOAD = ${pyLit(plan.createPayload)}
UNIQUE_CREATE = ${pyLit(plan.uniqueCreate)}
${plan.updatePayload !== undefined ? `\nUPDATE_PAYLOAD = ${pyLit(plan.updatePayload)}\nUNIQUE_UPDATE = ${pyLit(plan.uniqueUpdate)}\n` : ''}

def _unique(payload, fields):
    """Copy of a payload with the given string fields suffixed (field -> max length or None)."""
    out = copy.deepcopy(payload)
    suffix = "-" + uuid.uuid4().hex[:6]
    for key, max_len in fields.items():
        if isinstance(out, dict) and isinstance(out.get(key), str):
            base = out[key] if max_len is None else out[key][: max(0, max_len - len(suffix))]
            out[key] = base + suffix
    return out


class ${cls}:
    """${c.key} creates, ${d.key} removes."""

    def __init__(self, api, contract):
        self.api = api
        self.contract = contract

    @staticmethod
    def new_create_payload():
        return _unique(CREATE_PAYLOAD, UNIQUE_CREATE)
${plan.updatePayload !== undefined ? `
    @staticmethod
    def new_update_payload():
        return _unique(UPDATE_PAYLOAD, UNIQUE_UPDATE)
` : ''}
    def create(self, data=None):
        """${c.key}: creates a resource for a test and returns (id, body)."""
        res = self.api.${c.method}(${str(c.path.replace(/^\//, ''))}, json=self.new_create_payload() if data is None else data)
        ${assertSuccess(c)}
        body = self.contract.expect(res, ${str(c.method)}, ${str(c.path)})
        resource_id = read_pointer(body, ${str(chain.idPointer)})
        assert resource_id not in (None, ""), "identifier at $response.body#${chain.idPointer}"
        return str(resource_id), body

    def remove(self, resource_id):
        """${d.key}: best-effort cleanup, never fails the test. A record it cannot remove is reported (404 = already gone)."""
        try:
            res = self.api.delete(${pathExpr(d, chain.param)})
        except Exception:  # noqa: BLE001 - cleanup must not hide the real failure
            res = None
        if res is None or (not res.ok and res.status_code != 404):
            report_cleanup_failure(${str(d.key)}, resource_id, res.status_code if res is not None else "no response")

    def remove_if_created(self, res):
        """Cleanup for negative create cases: if the API wrongly accepted the payload, delete what it created."""
        if not res.ok:
            return
        try:
            resource_id = read_pointer(res.json(), ${str(chain.idPointer)})
        except ValueError:
            return
        if resource_id not in (None, ""):
            self.remove(resource_id)
`;
}

